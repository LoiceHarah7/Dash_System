def parse_tracking_tsv(raw_tsv, site="Lilongwe"):
    records = []
    lines = raw_tsv.strip().split("\n")
    if not lines:
        return records
    header = [h.strip() for h in lines[0].split("\t")]
    for line in lines[1:]:
        if not line.strip():
            continue
        parts = [p.strip() for p in line.split("\t")]
        # Ensure we have at least 6 fields
        while len(parts) < 6:
            parts.append("")
        pid = parts[0]
        if not pid:
            continue
        q_date = parts[1] or None
        dental_date = parts[2] or None
        endo_status = parts[3].upper() if parts[3] else None
        if endo_status not in ("YES", "NO"):
            if endo_status:
                endo_status = endo_status
            else:
                endo_status = None
        endo_date = parts[4] or None
        comment = parts[5] or None
        records.append({
            "site": site,
            "pid": pid,
            "questionnaire_date": q_date,
            "dental_date": dental_date,
            "endo_status": endo_status,
            "endo_date": endo_date,
            "comment": comment
        })
    return records


